import nodemailer from 'nodemailer';

const RECIPIENT = 'sintija.markus@startschool.org';

function esc(s) {
  return String(s ?? '').replace(/[&<>"']/g, (c) =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c])
  );
}

const transporter = nodemailer.createTransport({
  host: process.env.SMTP_HOST || 'smtp.gmail.com',
  port: parseInt(process.env.SMTP_PORT, 10) || 587,
  secure: false,
  auth: {
    user: process.env.SMTP_USER,
    pass: process.env.SMTP_PASS,
  },
});

function formatProfile(profile) {
  const parse = (v) => {
    if (!v) return [];
    try { return JSON.parse(v); } catch { return [v]; }
  };

  const didYouKnow = parse(profile.did_you_know);
  const askMeAbout = parse(profile.ask_me_about);
  const experience = parse(profile.experience);
  const lifeAtGlance = parse(profile.life_at_glance);
  const dreams = parse(profile.dreams);
  const inspirations = parse(profile.inspirations);

  return `
STARTSCHOOL HUMAN MAP — ${profile.name}
${'='.repeat(50)}

${profile.intro || ''}

${profile.motto ? `MOTTO: "${profile.motto}"` : ''}

01 / DID YOU KNOW? 💡
${didYouKnow.map((f, i) => `  ${i + 1}. ${f}`).join('\n')}

02 / ASK ME ABOUT… 💬
${askMeAbout.map((t) => `  • ${t}`).join('\n')}

03 / MY SUPERPOWER ⚡
  ${profile.superpower_title || 'N/A'}
  ${profile.superpower_description || ''}

EXPERIENCE & ACHIEVEMENTS
${experience.map((e) => `  • ${typeof e === 'string' ? e : `${e.title}: ${e.description}`}`).join('\n')}

LIFE AT A GLANCE
${lifeAtGlance.map((f) => `  • ${f}`).join('\n')}

DREAMS & WISHES
${dreams.map((d) => `  • ${d}`).join('\n')}

WHAT INSPIRES ME
${inspirations.map((i) => `  • ${i}`).join('\n')}
`.trim();
}

export async function sendProfileEmail(profile, interviewId) {
  if (!process.env.SMTP_USER || !process.env.SMTP_PASS) {
    console.warn('SMTP not configured — skipping email send');
    return false;
  }

  const text = formatProfile(profile);
  const mapUrl = process.env.PUBLIC_URL
    ? `${process.env.PUBLIC_URL}/map/${profile.id}`
    : `https://interview.coverconnect.co/map/${profile.id}`;

  const parse = (v) => { try { return JSON.parse(v); } catch { return []; } };
  const dyk = parse(profile.did_you_know);
  const ama = parse(profile.ask_me_about);

  const html = `
<div style="font-family: 'Space Grotesk', Arial, sans-serif; max-width: 600px; margin: 0 auto; background: #0A1628; color: #E2E8F0; padding: 32px; border-radius: 12px;">
  <div style="text-align: center; margin-bottom: 24px;">
    <h1 style="color: #0066FF; margin: 0;">STARTSCHOOL</h1>
    <h2 style="color: #FF3399; font-weight: 400; margin: 4px 0 0;">HUMAN MAP</h2>
  </div>

  <h2 style="color: white; margin-bottom: 8px;">${esc(profile.name)}</h2>
  <p style="color: #94A3B8;">${esc(profile.intro)}</p>

  ${profile.motto ? `<blockquote style="border-left: 3px solid #FF3399; padding-left: 16px; color: #CBD5E1; font-style: italic;">"${esc(profile.motto)}"</blockquote>` : ''}

  <h3 style="color: #0066FF;">01 / DID YOU KNOW? 💡</h3>
  <ul style="color: #E2E8F0;">${dyk.map((f) => `<li>${esc(f)}</li>`).join('')}</ul>

  <h3 style="color: #0066FF;">02 / ASK ME ABOUT… 💬</h3>
  <div>${ama.map((t) => `<span style="display: inline-block; background: #1A2A44; color: #0066FF; padding: 4px 12px; border-radius: 999px; margin: 4px 4px 4px 0; font-size: 14px;">${esc(t)}</span>`).join('')}</div>

  <h3 style="color: #FF3399;">03 / MY SUPERPOWER ⚡</h3>
  <div style="background: linear-gradient(135deg, #0066FF22, #FF339922); border: 1px solid #FF339944; border-radius: 12px; padding: 16px;">
    <strong style="color: white; font-size: 18px;">${esc(profile.superpower_title)}</strong>
    <p style="color: #CBD5E1; margin: 8px 0 0;">${esc(profile.superpower_description)}</p>
  </div>

  <div style="text-align: center; margin-top: 32px;">
    <a href="${esc(mapUrl)}" style="display: inline-block; background: #0066FF; color: white; padding: 12px 32px; border-radius: 8px; text-decoration: none; font-weight: 600;">View Full Human Map</a>
  </div>

  <p style="color: #64748B; font-size: 12px; text-align: center; margin-top: 24px;">Generated by interview.coverconnect.co — StartSchool Human Map</p>
</div>`;

  await transporter.sendMail({
    from: process.env.SMTP_FROM || process.env.SMTP_USER,
    to: RECIPIENT,
    subject: `New Human Map: ${profile.name} — StartSchool`,
    text,
    html,
  });

  return true;
}
